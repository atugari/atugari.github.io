// Check that the collection card exists only in the notebook play menu.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const {parseHTML}=require(process.argv[2]||'linkedom');
const source=fs.readFileSync(path.join(__dirname,'../puzzles/navigation.js'),'utf8');
const {document}=parseHTML('<html lang="ja"><head></head><body><main></main></body></html>');
const observers=[];
const window={document,requestAnimationFrame:fn=>fn(),addEventListener(){},MutationObserver:class{constructor(fn){observers.push(fn)}observe(){}}};
vm.runInNewContext(source,{window});
const main=document.querySelector('main');
const count=()=>document.querySelectorAll('[data-collection-entry]').length;
assert.equal(count(),0);
main.innerHTML='<div class="homechoices"><button data-action="open-notebook">数字のパズル</button></div>';
observers[0]();
const link=document.querySelector('[data-collection-entry]');
assert.equal(count(),1);
assert.equal(link.getAttribute('href'),'/nanpure/collection/');
assert.equal(link.getAttribute('target'),'_top');
assert.equal(link.querySelector('strong').textContent,'すぐ遊べるナンプレ集');
link.after(link.cloneNode(true));
observers[0]();
assert.equal(count(),1);
assert.strictEqual(document.querySelector('[data-collection-entry]'),link);
main.innerHTML='<div class="homechoices"><button data-action="start">問題を作る</button></div>';
observers[0]();
assert.equal(count(),0);
console.log('PASS collection entry: play menu only, stable destination, deduplication and cleanup');
