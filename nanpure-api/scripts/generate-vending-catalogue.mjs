import { readFileSync, writeFileSync } from 'node:fs';
import { listProfiles } from '../../android/nanpure-vending-worker/prepare-engine.cjs';

const profiles = listProfiles().sort((a, b) => a.key.localeCompare(b.key, 'en'));
if (profiles.length !== 427) throw new Error('Check the vending catalogue release before changing its size.');
const sql = value => value == null || value === '' ? 'NULL'
  : Number.isSafeInteger(value) ? String(value)
    : "'" + value.replaceAll("'", "''") + "'";
const records = profiles.map(p => [p.key, p.kind, p.n, p.level, p.complexity, p.multiShape, p.linkedShape,
  p.key === 'normal:100:1:0::::' ? 'server' : 'device']);
const output = [
  '-- Generated by node scripts/generate-vending-catalogue.mjs from the fixed Android release.',
  '-- Existing pilot rows retain their independent verification and stock targets.',
  'INSERT OR IGNORE INTO vending_catalogue (profile,kind,n,level,complexity,multi_shape,linked_shape,verification) VALUES',
  records.map(row => '  (' + row.map(sql).join(',') + ')').join(',\n') + ';', ''
].join('\n');
const migration = new URL('../migrations/0014_vending_catalogue_profiles.sql', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(migration, 'utf8') !== output) throw new Error('The vending catalogue migration differs from the Android release.');
} else {
  writeFileSync(migration, output);
}
